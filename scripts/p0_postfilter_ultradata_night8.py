#!/usr/bin/env python3
"""Postfilter Qwen-kept records: exact cross-corpus dedup and review-only flags.

This is an audit index, not a training corpus. No source text is rewritten.
"""

from __future__ import annotations

import argparse
import ast
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import re
import tempfile
import unicodedata


SOURCE_CODE = "ultradata_code_l2_py"
SOURCE_MATH = "ultradata_math_l2_preview"


def read_jsonl(path: Path):
    if not path.exists():
        return
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                yield json.loads(line)


def normalized_text(text: str, max_blank_line_run: int = 3) -> str:
    """Match p0_data_pipeline.normalize_text, including code indentation."""
    text = unicodedata.normalize("NFC", text.replace("\x00", ""))
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    lines = [line.rstrip(" \t") for line in text.split("\n")]
    result = []
    blank_run = 0
    for line in lines:
        if line:
            blank_run = 0
            result.append(line)
        else:
            blank_run += 1
            if blank_run <= max_blank_line_run:
                result.append("")
    return "\n".join(result).strip()


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def quality_flags(source: str, text: str, locator: str = "") -> list[str]:
    flags = []
    stripped = text.strip()
    if source == SOURCE_CODE:
        path_parts = {part.casefold() for part in locator.replace("\\", "/").split("/")[2:-1]}
        if path_parts & {"vendored", "thirdparty", "vendorized"}:
            flags.append("code_vendored_path")
        if len(stripped) < 160:
            flags.append("code_short")
        try:
            ast.parse(text)
        except (SyntaxError, ValueError, UnicodeError):
            # Py2 and snippets can fail Py3 parsing; never an automatic reject.
            flags.append("code_python3_parse_failure")
        if len(text) > 500 and text.count("\n") <= 2:
            flags.append("code_flattened_or_minified")
        if re.search(r"(?i)automatically generated|generated by|do not edit", text[:500]):
            flags.append("code_generated_header")
    elif source == SOURCE_MATH:
        if len(stripped) < 300:
            flags.append("math_short")
        if re.search(r"(?i)\b(up vote|down vote|favorite)\b", text[:500]):
            flags.append("math_forum_chrome")
    else:
        limit = 400 if source == "ultrafineweb_en" else 250
        if len(stripped) < limit:
            flags.append("web_short")
        chrome = re.findall(r"(?i)privacy policy|cookie policy|accept cookies|terms of service|sign in|log in", text[:1200])
        if len(chrome) >= 2 and len(stripped) < 2500:
            flags.append("web_navigation_cluster")
        lines = [line.strip() for line in text.splitlines() if line.strip()]
        if len(lines) >= 10 and len(set(lines)) / len(lines) < 0.3:
            flags.append("web_repeated_lines")
    return flags


def load_existing(wave1_index: Path, extra_hashes: Path) -> dict[str, set[str]]:
    import pyarrow.parquet as pq

    existing = defaultdict(set)
    pf = pq.ParquetFile(wave1_index)
    for batch in pf.iter_batches(batch_size=8192, columns=["normalized_sha256", "split"]):
        data = batch.to_pydict()
        for digest, split in zip(data["normalized_sha256"], data["split"]):
            existing[digest].add("wave1:" + str(split))
    manifest = json.loads(extra_hashes.with_suffix(".manifest.json").read_text())
    if sha256_file(extra_hashes) != manifest["sha256"]:
        raise ValueError("approved/generated hash transfer mismatch")
    for row in read_jsonl(extra_hashes):
        existing[row["normalized_sha256"]].add(row["corpus"] + ":" + str(row["split"]))
    return existing


def load_labels(root: Path) -> dict[str, dict]:
    labels = {}
    for band in ("heavy", "medium", "light"):
        for shard in range(8):
            path = root / "results" / band / f"shard-{shard}.results.jsonl"
            for row in read_jsonl(path):
                if row["status"] != "ok":
                    continue
                doc_id, = json.loads(row["source_id"])
                if doc_id in labels or row["annotation"]["document_id"] != doc_id:
                    raise ValueError(f"duplicate/mismatched Qwen result: {doc_id}")
                labels[doc_id] = row["annotation"]
    return labels


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--night-root", type=Path, required=True)
    ap.add_argument("--wave1-index", type=Path, required=True)
    ap.add_argument("--extra-hashes", type=Path, required=True)
    ap.add_argument("--output-dir", type=Path, required=True)
    args = ap.parse_args()
    if args.output_dir.exists():
        raise FileExistsError(args.output_dir)
    finished_path = args.night_root / "FINISHED8.json"
    finished = json.loads(finished_path.read_text())
    if finished["expected"] != 150000 or finished["ok"] != 149777:
        raise ValueError("night8 completion marker differs from audited run")
    labels = load_labels(args.night_root)
    keep_ids = {doc_id for doc_id, value in labels.items() if value["decision"] == "keep"}
    if len(keep_ids) != 80409:
        raise ValueError(f"Qwen keep count changed: {len(keep_ids)}")
    existing = load_existing(args.wave1_index, args.extra_hashes)
    rows, seen_ids = [], set()
    for band in ("heavy", "medium", "light"):
        for shard in range(8):
            path = args.night_root / "inputs" / band / f"shard-{shard}.input.jsonl"
            for row in read_jsonl(path):
                doc_id = row["document_id"]
                if doc_id not in keep_ids:
                    continue
                if doc_id in seen_ids:
                    raise ValueError(f"duplicate input ID: {doc_id}")
                seen_ids.add(doc_id)
                envelope = json.loads(row["review_payload"])
                if envelope["document_id"] != doc_id:
                    raise ValueError(f"review payload ID mismatch: {doc_id}")
                text = envelope["document_text"]
                digest = hashlib.sha256(normalized_text(text).encode("utf-8")).hexdigest()
                qwen = labels[doc_id]
                rows.append({
                    "document_id": doc_id, "source_id": row["source_id"],
                    "source_locator": envelope["source_locator"],
                    "raw_row": row["raw_row"], "upstream_score": row["upstream_score"],
                    "text_chars": len(text), "prompt_tokens_est": row["prompt_tokens_est"],
                    "normalized_sha256": digest, "quality_flags": quality_flags(row["source_id"], text,
                                                                                envelope["source_locator"]),
                    "qwen_quality": qwen["quality"], "qwen_confidence": qwen["confidence"],
                })
    if seen_ids != keep_ids:
        raise ValueError(f"Qwen keep input mismatch: {len(keep_ids - seen_ids)} missing")

    groups = defaultdict(list)
    for row in rows:
        groups[row["normalized_sha256"]].append(row)
    canonical = {}
    for digest, group in groups.items():
        best = min(group, key=lambda r: (-r["qwen_quality"], -r["qwen_confidence"],
                                         -r["text_chars"], r["document_id"]))
        canonical[digest] = best["document_id"]
    by_source = defaultdict(Counter)
    flags_count = Counter()
    duplicate_corpora = Counter()
    code_repos = set()
    for row in rows:
        source = row["source_id"]
        counter = by_source[source]
        counter["qwen_keep"] += 1
        digest = row["normalized_sha256"]
        hits = sorted(existing.get(digest, ()))
        row["existing_corpus_hits"] = hits
        row["duplicate_of_current_id"] = (canonical[digest]
                                            if canonical[digest] != row["document_id"] else None)
        if hits:
            counter["exact_existing_duplicate"] += 1
            duplicate_corpora.update(hits)
        if row["duplicate_of_current_id"]:
            counter["exact_current_duplicate"] += 1
        flags_count.update(row["quality_flags"])
        if row["quality_flags"]:
            counter["quality_flagged"] += 1
        if hits or row["duplicate_of_current_id"]:
            row["postfilter_status"] = "exact_duplicate"
        elif row["quality_flags"]:
            row["postfilter_status"] = "needs_review"
        else:
            row["postfilter_status"] = "quality_candidate_license_pending"
            counter["quality_candidate_license_pending"] += 1
        row["license_gate"] = ("source_repository_license_pending" if source == SOURCE_CODE
                               else "upstream_source_rights_pending")
        if source == SOURCE_CODE:
            parts = row["source_locator"].split("/", 2)
            if len(parts) >= 2:
                code_repos.add("/".join(parts[:2]))
    summary = {
        "stage": "night8_postfilter_audit_not_training_approved",
        "qwen_keep": len(keep_ids),
        "finished8_sha256": sha256_file(finished_path),
        "wave1_index_sha256": sha256_file(args.wave1_index),
        "extra_hashes_sha256": sha256_file(args.extra_hashes),
        "normalization": "p0_data_pipeline.normalize_text_max_blank_line_run_3",
        "dedup": "normalized_sha256_exact_only_no_near_dedup",
        "per_source": {name: dict(sorted(values.items())) for name, values in sorted(by_source.items())},
        "flags": dict(flags_count.most_common()),
        "existing_hit_corpora": dict(duplicate_corpora.most_common()),
        "unique_code_repositories": len(code_repos),
        "license_gate": "all_four_sources_pending",
    }
    args.output_dir.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".night8-postfilter-", dir=args.output_dir.parent) as tmp:
        out = Path(tmp)
        index = out / "postfilter_index.jsonl"
        with index.open("w", encoding="utf-8") as handle:
            for row in sorted(rows, key=lambda r: r["document_id"]):
                handle.write(json.dumps(row, ensure_ascii=False, sort_keys=True) + "\n")
        summary["index_sha256"] = sha256_file(index)
        (out / "summary.json").write_text(json.dumps(summary, ensure_ascii=False, indent=2) + "\n")
        out.rename(args.output_dir)
    print(json.dumps(summary, ensure_ascii=False), flush=True)


if __name__ == "__main__":
    main()
